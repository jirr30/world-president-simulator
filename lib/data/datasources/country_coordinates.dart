  static String? resolveId(String name) {
    final lower = name.toLowerCase().trim();
    if (nameOverrides.containsKey(lower)) return nameOverrides[lower];
    final slug = nameToId(name);
    if (all.containsKey(slug)) return slug;
    return null;
  }
